import assert from 'node:assert/strict'
import { readdirSync, readFileSync } from 'node:fs'
import { test } from 'node:test'

import { PGlite } from '@electric-sql/pglite'

import { buildSetupSqlBundle } from '../utils/setup-sql'

const schema = readFileSync('docs/schema.sql', 'utf8').replace(
  'CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;',
  ''
)
const files = [
  { file: 'docs/schema.sql', sql: schema },
  ...readdirSync('docs/migrations')
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((f) => ({
      file: `docs/migrations/${f}`,
      sql: readFileSync(`docs/migrations/${f}`, 'utf8')
    }))
]
const bundle = buildSetupSqlBundle(files)
const admin = '11111111-1111-4111-8111-111111111111'
const person = '22222222-2222-4222-8222-222222222222'
const token = 'a'.repeat(64)

test('full setup bundle can be replayed and recover a partial schema replay without losing data or private function identities', async () => {
  const db = new PGlite()
  try {
    await db.exec(`
      CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS;
      CREATE SCHEMA auth; CREATE SCHEMA storage; CREATE SCHEMA extensions;
      CREATE TABLE auth.users(id uuid PRIMARY KEY, email text, email_confirmed_at timestamptz, created_at timestamptz DEFAULT now());
      CREATE TABLE storage.buckets(id text PRIMARY KEY,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      CREATE TABLE storage.objects(id uuid PRIMARY KEY,bucket_id text,name text);
      ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
      CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      GRANT USAGE ON SCHEMA auth TO authenticated;
      GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated;
      ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
    `)
    await db.exec(bundle)
    const history = await db.query<{ migration_id: string; applied_at: Date }>(
      'SELECT migration_id, applied_at FROM public.app_migrations ORDER BY migration_id'
    )
    assert.deepEqual(
      history.rows.map((row) => row.migration_id),
      files.map(({ file }) => file).sort()
    )
    const privileges = await db.query<{ role: string; allowed: boolean }>(
      "SELECT role, has_table_privilege(role, 'public.app_migrations', 'SELECT,INSERT,UPDATE,DELETE') AS allowed FROM unnest(ARRAY['anon','authenticated']) AS role"
    )
    assert.ok(privileges.rows.every((row) => !row.allowed))
    await db.query(
      'INSERT INTO auth.users(id,email,email_confirmed_at) VALUES ($1,$2,now())',
      [admin, 'owner@example.com']
    )
    await db.query(
      "UPDATE profiles SET role='admin',is_active=true WHERE id=$1",
      [admin]
    )
    await db.query(
      "INSERT INTO persons(id,full_name,gender,is_deceased,birth_year_from,birth_year_to,memorial_day,memorial_month,memorial_calendar) VALUES ($1,'Ancestor','male',true,1880,1885,5,3,'lunar')",
      [person]
    )
    await db.query(
      "INSERT INTO family_intake_links(token_hash,title,root_person_id,expires_at,created_by) VALUES (md5($1),$2,$3,now()+interval '1 day',$4)",
      [token, 'Family branch', person, admin]
    )
    const payload = {
      anchor_id: person,
      sender_name: 'Sender',
      sender_contact: 'sender@example.com',
      note: '',
      people: [
        {
          client_id: '33333333-3333-4333-8333-333333333333',
          relation: 'child',
          relative_to: 'anchor',
          data: {
            full_name: 'Pending child',
            gender: 'male',
            is_deceased: false
          }
        }
      ]
    }
    await db.query('SELECT submit_family_intake($1,$2::jsonb)', [
      token,
      JSON.stringify(payload)
    ])
    const snapshot = () =>
      Promise.all(
        [
          'profiles',
          'persons',
          'relationships',
          'person_details_private',
          'custom_events',
          'family_intake_links',
          'family_intake_submissions'
        ].map((table) => db.query(`SELECT * FROM public.${table} ORDER BY 1`))
      )
    const privateFunctions = () =>
      db.query(
        "SELECT oid,proname,pg_get_function_identity_arguments(oid) AS args FROM pg_proc WHERE pronamespace='private'::regnamespace ORDER BY proname,oid"
      )
    const dataBefore = await snapshot()
    const functionsBefore = await privateFunctions()
    await db.exec(
      'CREATE FUNCTION public.test_admin_type_dependency() RETURNS SETOF public.admin_user_data LANGUAGE sql AS $$ SELECT NULL::public.admin_user_data WHERE false $$;'
    )

    // Replay the same schema + complete migration order generated by /setup.
    await db.exec(bundle)
    await db.exec(bundle)
    assert.deepEqual(
      (
        await db.query(
          'SELECT migration_id, applied_at FROM public.app_migrations ORDER BY migration_id'
        )
      ).rows,
      history.rows
    )
    // Old SQL Editor bundles applied SQL without adding history entries.
    await db.query(
      "DELETE FROM public.app_migrations WHERE migration_id LIKE 'docs/migrations/20261019%'"
    )
    await db.exec(bundle)
    const restoredHistory = (
      await db.query<{ migration_id: string; applied_at: Date }>(
        'SELECT migration_id, applied_at FROM public.app_migrations ORDER BY migration_id'
      )
    ).rows
    assert.equal(restoredHistory.length, files.length)
    assert.deepEqual(
      restoredHistory.filter((row) => !row.migration_id.includes('/20261019')),
      history.rows.filter((row) => !row.migration_id.includes('/20261019'))
    )
    assert.deepEqual(await snapshot(), dataBefore)
    assert.deepEqual(await privateFunctions(), functionsBefore)
    assert.ok(
      (
        await db.query<{ function: unknown }>(
          "SELECT to_regprocedure('public.test_admin_type_dependency()') AS function"
        )
      ).rows[0].function
    )

    // Simulate the earlier schema having completed before the hardening failed.
    await db.exec(schema)
    await db.exec(
      'CREATE TRIGGER test_replay_updated_at BEFORE UPDATE ON public.persons FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at(); ALTER TABLE public.persons DISABLE TRIGGER test_replay_updated_at;'
    )
    await db.exec(bundle)
    assert.deepEqual(await snapshot(), dataBefore)
    assert.deepEqual(await privateFunctions(), functionsBefore)
    const trigger = await db.query<{
      schema: string
      name: string
      enabled: string
    }>(
      "SELECT n.nspname AS schema,p.proname AS name,t.tgenabled AS enabled FROM pg_trigger t JOIN pg_proc p ON p.oid=t.tgfoid JOIN pg_namespace n ON n.oid=p.pronamespace WHERE t.tgname='test_replay_updated_at'"
    )
    assert.deepEqual(trigger.rows[0], {
      schema: 'private',
      name: 'handle_updated_at',
      enabled: 'D'
    })
    const publicHelpers = await db.query<{
      proname: string
      prosecdef: boolean
    }>(
      "SELECT proname,prosecdef FROM pg_proc WHERE pronamespace='public'::regnamespace AND proname IN ('handle_updated_at','handle_new_user','handle_first_user_confirmation','is_admin','is_active_user','is_editor','get_admin_users','set_user_role','delete_user','admin_create_user','set_user_active_status')"
    )
    assert.equal(publicHelpers.rows.length, 8)
    assert.ok(publicHelpers.rows.every((row) => !row.prosecdef))
    await db.transaction(async (tx) => {
      await tx.exec('SET LOCAL ROLE authenticated')
      await tx.query("SELECT set_config('request.jwt.claim.sub',$1,true)", [
        admin
      ])
      assert.equal(
        (
          await tx.query<{ allowed: boolean }>(
            'SELECT public.is_admin() AS allowed'
          )
        ).rows[0].allowed,
        true
      )
      assert.equal((await tx.query('SELECT * FROM persons')).rows.length, 1)
      assert.equal(
        (await tx.query('SELECT * FROM public.get_admin_users()')).rows.length,
        1
      )
    })
    await db.query(
      'INSERT INTO auth.users(id,email,email_confirmed_at) VALUES ($1,$2,now())',
      ['44444444-4444-4444-8444-444444444444', 'new@example.com']
    )
    assert.deepEqual(
      (
        await db.query(
          "SELECT role,is_active FROM profiles WHERE id='44444444-4444-4444-8444-444444444444'"
        )
      ).rows[0],
      { role: 'member', is_active: false }
    )
    await db.query('UPDATE persons SET note=$1 WHERE id=$2', [
      'Trigger still works',
      person
    ])
    assert.ok(
      (
        await db.query<{ updated_at: string }>(
          'SELECT updated_at FROM persons WHERE id=$1',
          [person]
        )
      ).rows[0].updated_at
    )
  } finally {
    await db.close()
  }
})

test('setup failure rolls back schema and history together', async () => {
  const db = new PGlite()
  try {
    await db.exec('CREATE ROLE anon; CREATE ROLE authenticated;')
    const failing = buildSetupSqlBundle([
      {
        file: 'docs/schema.sql',
        sql: 'BEGIN;\r\nCREATE TABLE public.setup_probe(id int);\r\nCOMMIT;\r\n'
      },
      {
        file: 'docs/migrations/20990101000000_fail.sql',
        sql: 'SELECT missing_setup_function();'
      }
    ])
    await assert.rejects(db.exec(failing))
    await db.exec('ROLLBACK;')
    const result = await db.query<{
      tracker: string | null
      probe: string | null
    }>(
      "SELECT to_regclass('public.app_migrations') AS tracker, to_regclass('public.setup_probe') AS probe"
    )
    assert.deepEqual(result.rows, [{ tracker: null, probe: null }])
  } finally {
    await db.close()
  }
})
